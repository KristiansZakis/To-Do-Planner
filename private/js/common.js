const App = {
    user: null,
    lang: 'en',
    t(key) { return (I18N[this.lang] && I18N[this.lang][key]) || I18N.en[key] || key; },

    async api(url, method = 'GET', body) {
        const res = await fetch(url, {
            method,
            headers: body !== undefined ? { 'Content-Type': 'application/json' } : undefined,
            body: body !== undefined ? JSON.stringify(body) : undefined,
        });
        if (res.status === 401) { window.location.href = '/login'; throw new Error('Not logged in'); }
        const data = await res.json().catch(() => ({}));
        if (!res.ok) throw new Error(data.error || 'Something went wrong.');
        return data;
    },

    applySettings(u) {
        this.lang = u.language || 'en';
        document.documentElement.lang = this.lang;
        document.documentElement.dataset.theme = u.theme || 'dark';
        document.documentElement.style.fontSize = (u.text_size || 16) + 'px';
        document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = this.t(el.dataset.i18n); });
        document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = this.t(el.dataset.i18nTitle); });
    },

    async init() {
        this.user = await this.api('/api/me');
        this.applySettings(this.user);
        return this.user;
    },

    async logout() {
        await fetch('/api/logout', { method: 'POST' });
        window.location.href = '/login';
    },
};

function esc(s) {
    return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
